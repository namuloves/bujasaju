#!/usr/bin/env python3
"""
subset-og-fonts.py — builds the small NotoSansKR fonts used by /api/og.

    python3 scripts/subset-og-fonts.py

Why: the share-card route (src/app/api/og/route.tsx) needs Korean glyphs, and
the full NotoSansKR Bold + Regular TTFs are ~9.4MB together. The card only
ever draws a handful of strings, so we ship a subset instead:

    public/fonts/og/NotoSansKR-Bold.subset.woff
    public/fonts/og/NotoSansKR-Regular.subset.woff

(WOFF, not WOFF2 — satori, which renders the image, reads TTF/OTF/WOFF only.)

The subset contains:
  - Basic Latin, Latin-1 / Latin Extended-A and common punctuation/currency
  - the 2,350 everyday Hangul syllables of KS X 1001
  - every character that appears in the dataset's name / company / source /
    nationality fields (so every current billionaire renders from the subset)
  - every Hangul syllable written in the route file itself

It also writes src/lib/og/fontCoverage.ts with two sets:
  - OG_FONT_CHARS: characters present in BOTH subset faces
  - OG_FONT_UNAVAILABLE_CHARS: characters we asked for that NotoSansKR itself
    lacks (some Latin Extended-A letters), where the full font can't help
The route checks its text against them and falls back to the full fonts only
when a character is outside both — i.e. the full font might have it. So a rare
syllable in a future name renders correctly (just slower) instead of as an
empty box, and unrenderable letters don't trigger a pointless 9.4MB load.

Re-run this whenever the dataset gains a name that uses new characters, then
commit the regenerated files. Requires: pip install fonttools
"""
import json
import re
import sys
from pathlib import Path

from fontTools import subset
from fontTools.ttLib import TTFont

ROOT = Path(__file__).resolve().parent.parent
FONT_DIR = ROOT / "public" / "fonts"
OUT_DIR = FONT_DIR / "og"
COVERAGE_TS = ROOT / "src" / "lib" / "og" / "fontCoverage.ts"
ROUTE_TS = ROOT / "src" / "app" / "api" / "og" / "route.tsx"
DATASET = ROOT / "private-data" / "billionaires.json"

FACES = {
    "Bold": FONT_DIR / "NotoSansKR-Bold.ttf",
    "Regular": FONT_DIR / "NotoSansKR-Regular.ttf",
}
DATASET_FIELDS = ("name", "nameKo", "company", "companyKo", "source", "nationality")


def ks_x_1001_hangul() -> set[str]:
    """The 2,350 Hangul syllables of KS X 1001 (EUC-KR rows 0xB0-0xC8)."""
    out: set[str] = set()
    for row in range(0xB0, 0xC9):
        for col in range(0xA1, 0xFF):
            try:
                out.add(bytes([row, col]).decode("euc_kr"))
            except UnicodeDecodeError:
                pass
    assert len(out) == 2350, f"expected 2350 KS X 1001 syllables, got {len(out)}"
    return out


def baseline_chars() -> set[str]:
    chars = {chr(c) for c in range(0x20, 0x7F)}  # Basic Latin
    chars |= {chr(c) for c in range(0xA0, 0x180)}  # Latin-1 + Latin Extended-A
    chars |= {chr(c) for c in range(0x2010, 0x2028)}  # dashes, quotes, bullets, ellipsis
    chars |= set("₩€£¥~≈×→·《》「」『』")
    chars |= {chr(c) for c in range(0x3131, 0x318F)}  # Hangul compatibility jamo
    return chars


def dataset_chars() -> set[str]:
    chars: set[str] = set()
    for person in json.loads(DATASET.read_text(encoding="utf8")):
        for field in DATASET_FIELDS:
            value = person.get(field)
            if isinstance(value, str):
                chars |= set(value)
        for alias in person.get("aliasesKo") or []:
            chars |= set(alias)
    return chars


def route_hangul() -> set[str]:
    return set(re.findall(r"[가-힣]", ROUTE_TS.read_text(encoding="utf8")))


def subset_face(src: Path, dest: Path, text: str) -> None:
    opts = subset.Options()
    opts.flavor = "woff"
    opts.layout_features = ["*"]  # keep kerning / shaping
    opts.hinting = False  # satori renders outlines only
    opts.notdef_outline = True
    opts.glyph_names = False
    opts.drop_tables += ["DSIG"]
    font = subset.load_font(str(src), opts)
    subsetter = subset.Subsetter(opts)
    subsetter.populate(text=text)
    subsetter.subset(font)
    dest.parent.mkdir(parents=True, exist_ok=True)
    subset.save_font(font, str(dest), opts)


def cmap_chars(path: Path) -> set[str]:
    cmap = TTFont(str(path)).getBestCmap()
    return {chr(cp) for cp in cmap if cp >= 0x20}


def ts_string_array(name: str, doc: str, chars: set[str]) -> str:
    ordered = "".join(sorted(chars))
    chunks = [ordered[i : i + 64] for i in range(0, len(ordered), 64)] or [""]
    lines = ",\n".join("  " + json.dumps(c, ensure_ascii=False) for c in chunks)
    return f"{doc}export const {name}: string = [\n{lines},\n].join('');\n"


def write_coverage(covered: set[str], unavailable: set[str]) -> None:
    COVERAGE_TS.parent.mkdir(parents=True, exist_ok=True)
    COVERAGE_TS.write_text(
        "// GENERATED by scripts/subset-og-fonts.py — do not edit by hand.\n\n"
        + ts_string_array(
            "OG_FONT_CHARS",
            "/** Characters present in both OG subset fonts\n"
            " *  (public/fonts/og/NotoSansKR-*.subset.woff). */\n",
            covered,
        )
        + "\n"
        + ts_string_array(
            "OG_FONT_UNAVAILABLE_CHARS",
            "/** Characters NotoSansKR itself lacks — falling back to the full font\n"
            " *  would not help, so they must not trigger the fallback. */\n",
            unavailable,
        ),
        encoding="utf8",
    )


def main() -> int:
    for face, path in FACES.items():
        if not path.exists():
            print(f"missing {path}", file=sys.stderr)
            return 1

    wanted = baseline_chars() | ks_x_1001_hangul() | dataset_chars() | route_hangul()
    text = "".join(sorted(wanted))
    print(f"requested {len(wanted)} characters")

    covered: set[str] | None = None
    for face, src in FACES.items():
        dest = OUT_DIR / f"NotoSansKR-{face}.subset.woff"
        subset_face(src, dest, text)
        have = cmap_chars(dest)
        covered = have if covered is None else covered & have
        print(f"{dest.relative_to(ROOT)}: {dest.stat().st_size / 1024:.0f}KB "
              f"(from {src.stat().st_size / 1024:.0f}KB, {len(have)} chars)")

    assert covered is not None
    unavailable = wanted - covered
    if unavailable:
        print(f"note: {len(unavailable)} requested characters are not in NotoSansKR "
              f"(recorded as unavailable): {''.join(sorted(unavailable))[:40]}…")
    write_coverage(covered, unavailable)
    print(f"wrote {COVERAGE_TS.relative_to(ROOT)} "
          f"({len(covered)} covered, {len(unavailable)} unavailable)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
