/**
 * Refresh src/lib/search-crawler-ips.json from the IP lists that the search
 * engines publish for verifying their crawlers.
 *
 *   npx tsx scripts/update-search-crawler-ips.ts
 *
 * proxy.ts and /api/deep-bio exempt these IPs from the per-IP rate limits
 * (see src/lib/searchCrawlers.ts). The lists change without notice, so rerun
 * this every few months. A crawler IP missing from the snapshot is not
 * blocked; it is only rate-limited like any other visitor.
 *
 * Sources:
 *   - Naver (Yeti): https://searchadvisor.naver.com/guide/seo-basic-firewall
 *   - Google (Googlebot and the other common crawlers):
 *     https://developers.google.com/crawling/docs/crawlers-fetchers/verify-google-requests
 *   - Bing (Bingbot): https://www.bing.com/toolbox/bingbot.json
 * Daum publishes no IP list, so Daum is not on it.
 */
import fs from 'node:fs';
import path from 'node:path';
import { BlockList } from 'node:net';

const SOURCES = {
  naver: 'https://searchadvisor.naver.com/doc/naverbot.json',
  google: 'https://developers.google.com/static/crawling/ipranges/common-crawlers.json',
  bing: 'https://www.bing.com/toolbox/bingbot.json',
} as const;

type Engine = keyof typeof SOURCES;

interface PublishedList {
  creationTime?: string;
  prefixes: Array<{ ipv4Prefix?: string; ipv6Prefix?: string }>;
}

interface EngineEntry {
  source: string;
  creationTime: string | null;
  ipv4: string[];
  ipv6: string[];
}

const OUT = path.join(__dirname, '..', 'src', 'lib', 'search-crawler-ips.json');

// Some hosts refuse requests without a browser-like User-Agent.
const UA = 'Mozilla/5.0 (compatible; bujasaju-crawler-ip-refresh)';

/** Throws on anything BlockList would reject at runtime. */
function checkCidr(cidr: string, type: 'ipv4' | 'ipv6'): void {
  const [addr, bits] = cidr.split('/');
  new BlockList().addSubnet(addr, Number(bits), type);
}

async function load(engine: Engine): Promise<EngineEntry> {
  const res = await fetch(SOURCES[engine], { headers: { 'User-Agent': UA } });
  if (!res.ok) throw new Error(`${engine}: HTTP ${res.status}`);
  const data = (await res.json()) as PublishedList;
  const ipv4: string[] = [];
  const ipv6: string[] = [];
  for (const p of data.prefixes ?? []) {
    if (p.ipv4Prefix) {
      checkCidr(p.ipv4Prefix, 'ipv4');
      ipv4.push(p.ipv4Prefix);
    }
    if (p.ipv6Prefix) {
      checkCidr(p.ipv6Prefix, 'ipv6');
      ipv6.push(p.ipv6Prefix);
    }
  }
  if (ipv4.length + ipv6.length === 0) throw new Error(`${engine}: empty list`);
  return { source: SOURCES[engine], creationTime: data.creationTime ?? null, ipv4, ipv6 };
}

async function main() {
  const engines = {} as Record<Engine, EngineEntry>;
  for (const engine of Object.keys(SOURCES) as Engine[]) {
    engines[engine] = await load(engine);
    const e = engines[engine];
    console.log(`${engine}: ${e.ipv4.length} IPv4 + ${e.ipv6.length} IPv6 prefixes (list dated ${e.creationTime})`);
  }
  const out = {
    _comment: 'Generated by scripts/update-search-crawler-ips.ts. Do not edit by hand.',
    generatedAt: new Date().toISOString(),
    engines,
  };
  fs.writeFileSync(OUT, JSON.stringify(out, null, 2) + '\n');
  console.log(`wrote ${path.relative(process.cwd(), OUT)}`);
}

main().catch((err) => {
  console.error(err);
  process.exit(1);
});
